from decimal import Decimal

from shop.prices import PRICES  # generated by scripts/gen_prices.py - do not edit prices.py by hand


class CartError(Exception):
    pass


def total(items):
    """items: list of (sku, qty). Returns Decimal total."""
    result = Decimal("0")
    for sku, qty in items:
        if sku not in PRICES:
            raise CartError(f"unknown sku {sku}")
        result += PRICES[sku] * qty
    return result
