"""Build evals/SCORECARD.md from results.csv: per-task A vs B, and per-skill evidence status.

  python evals/scorecard.py

A skill's status comes from the tasks that test it (the `Tests:` line in each TASK.md):
  proven    - B beats A by 2+ passes over 3+ runs each (e.g. 1/3 -> 3/3) in some task, never worse
  promising - B ahead but by less than that (e.g. 2/3 -> 3/3): noise until more runs confirm
  neutral   - tested, B equals A everywhere (value may be quality/consistency: read the notes)
  regressed - B worse than A in some task: investigate, candidate for pruning
  untested  - no task covers it, or no runs yet
"""
import csv
import re
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
EVALS = ROOT / "evals"


def task_tests():
    tests = {}
    for md in sorted((EVALS / "tasks").glob("*/TASK.md")):
        m = re.search(r"^Tests:(.*)$", md.read_text(encoding="utf-8"), re.M)
        tests[md.parent.name] = [t.strip() for t in m.group(1).split(".")[0].split(",")] if m else []
    return tests


def load_runs():
    runs = defaultdict(lambda: {"A": [], "B": []})
    with (EVALS / "results.csv").open(encoding="utf-8") as f:
        for row in csv.DictReader(f):
            if row["pass"] in ("0", "1") and row["condition"] in ("A", "B"):
                runs[row["task"]][row["condition"]].append(row)
    return runs


def summarize(rows):
    n = len(rows)
    passes = sum(r["pass"] == "1" for r in rows)
    tokens = [int(r["tokens"]) for r in rows if r["tokens"].isdigit()]
    return {"n": n, "passes": passes, "rate": passes / n if n else None,
            "all": n >= 3 and passes == n, "tokens": sum(tokens) / len(tokens) if tokens else None}


def verdict(a, b):
    if not a["n"] or not b["n"]:
        return "untested"
    if b["rate"] < a["rate"] or (a["all"] and not b["all"] and b["n"] >= 3):
        return "regressed"
    if b["rate"] > a["rate"]:
        gap = b["passes"] - a["passes"] * b["n"] / a["n"]
        return "proven" if min(a["n"], b["n"]) >= 3 and gap >= 2 else "promising"
    return "neutral"


def main():
    tests, runs = task_tests(), load_runs()
    skills = sorted(p.parent.name for p in (ROOT / "skills").glob("*/SKILL.md"))
    icon = {"proven": "✅ proven", "promising": "🟡 promising", "neutral": "➖ neutral", "regressed": "⚠️ regressed", "untested": "⬜ untested"}

    lines = ["# Scorecard", "", "_Generated by `python evals/scorecard.py` from `results.csv`. Do not edit by hand._", "",
             "## Tasks: baseline (A) vs Agent OS (B)", "",
             "| Task | A pass | B pass | pass^3 A / B | Avg tokens A → B | Verdict |", "|---|---|---|---|---|---|"]
    task_verdict = {}
    for task in sorted(tests):
        a, b = summarize(runs[task]["A"]), summarize(runs[task]["B"])
        v = task_verdict[task] = verdict(a, b)
        if not a["n"] and not b["n"]:
            lines.append(f"| {task} | – | – | – | – | {icon[v]} |")
            continue
        p3 = f"{'✅' if a['all'] else '❌'} / {'✅' if b['all'] else '❌'}"
        tok = (f"{a['tokens'] / 1000:.0f}k → {b['tokens'] / 1000:.0f}k ({(b['tokens'] / a['tokens'] - 1) * 100:+.0f}%)"
               if a["tokens"] and b["tokens"] else "–")
        lines.append(f"| {task} | {a['passes']}/{a['n']} | {b['passes']}/{b['n']} | {p3} | {tok} | {icon[v]} |")

    lines += ["", "## Skills: evidence status", "", "| Skill | Status | Evidence (tasks) |", "|---|---|---|"]
    order = ["regressed", "proven", "promising", "neutral", "untested"]
    for skill in skills:
        covering = [t for t, ts in tests.items() if skill in ts]
        verdicts = [task_verdict[t] for t in covering if task_verdict[t] != "untested"]
        status = next((s for s in order if s in verdicts), "untested")
        lines.append(f"| `{skill}` | {icon[status]} | {', '.join(covering) or 'no task yet'} |")

    lines += ["", "With 3 runs, only large gaps are meaningful. `neutral` can still mean better quality or consistency; "
                  "see the `notes` column in results.csv. Pruning rule: a skill that stays neutral and raises cost >20% "
                  "is a candidate to cut (via the `learn` skill)."]
    (EVALS / "SCORECARD.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {EVALS / 'SCORECARD.md'}")


if __name__ == "__main__":
    main()
